function tt(lang, key, vars = {}) {
  const s = (T[lang] && T[lang][key]) || T.en[key];
  if (s == null) throw new Error(`Missing term ${key}`);
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
}

// Every language must define every English key.
for (const l of Object.keys(T)) for (const k of Object.keys(T.en)) if (T[l][k] == null) throw new Error(`terms: ${l} is missing "${k}"`);

module.exports = { T, tt };
